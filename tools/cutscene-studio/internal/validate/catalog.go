package validate

import (
	"encoding/json"
	"fmt"
	"os"
	"sync"

	"mgs2-restoration/cutscene-studio/internal/datadir"
)

// EffectSpec is one row of the launcher catalog: what the game expects a packet for this
// composer id to look like. BodySize is the packet _size minus its 16-byte header, i.e.
// 16 + (16 if exec_type 1) + roundup16(DataSize).
type EffectSpec struct {
	ID       int32
	Name     string
	ExecType int32
	DataSize int // sizeof(Data), before the tail pad
	BodySize int
	HasName  bool     // Data starts with `int name`: the effect registers a control point under it
	AddSrc   []string // assets the launcher needs resident (P36)
}

// Catalog resolves a composer id (effect_id & 0xFFFFF).
type Catalog interface {
	Effect(composerID int32) (EffectSpec, bool)
}

type builtin struct{}

func (builtin) Effect(id int32) (EffectSpec, bool) {
	s, ok := builtinTable()[id]
	return s, ok
}

// DefaultCatalog is the 245-effect table derived from the effect catalog (effects.json,
// generated by tools/cnf2json.py into the data dir). Swap it for internal/catalog via
// Context.Catalog when a demo's stage table is known.
func DefaultCatalog() Catalog { return builtin{} }

// The table is not compiled in: it is derived from Konami's demoeffect.cnf, so it is read
// at first use from the same effects.json the editor loads. Without that file the table is
// empty -- every effect id is then "not in the catalog" (a Warn), and the catalog-dependent
// layout rules (P26 size, P27 exec_type, P34 names, P36 assets) have nothing to check against.
var (
	tableOnce sync.Once
	tableMu   sync.Mutex
	tablePath string
	table     map[int32]EffectSpec
	tableErr  error
)

// UseCatalogFile points the default catalog at a specific effects.json instead of the one
// found in the data dir. Call it before the first validation; later calls are ignored.
func UseCatalogFile(path string) {
	tableMu.Lock()
	tablePath = path
	tableMu.Unlock()
}

// DefaultCatalogLoaded reports whether the default catalog found its effects.json, and the
// load error if one occurred.
func DefaultCatalogLoaded() (bool, error) {
	t := builtinTable()
	return len(t) > 0, tableErr
}

func builtinTable() map[int32]EffectSpec {
	tableOnce.Do(func() {
		tableMu.Lock()
		p := tablePath
		tableMu.Unlock()
		if p == "" {
			p = datadir.File("effects.json")
		}
		table = map[int32]EffectSpec{}
		if p == "" {
			return
		}
		t, err := loadSpecs(p)
		if err != nil {
			tableErr = err
			return
		}
		table = t
	})
	return table
}

// catalogEntry is the subset of an effects.json record the validator needs.
type catalogEntry struct {
	ID             int32  `json:"id"`
	CName          string `json:"cname"`
	ExecType       int32  `json:"execType"`
	DataStructSize int    `json:"dataStructSize"`
	PacketBodySize int    `json:"packetBodySize"`
	Members        []struct {
		Name     string `json:"name"`
		CType    string `json:"ctype"`
		Pointer  int    `json:"pointer"`
		ArrayLen *int   `json:"arrayLen"`
	} `json:"members"`
	Options struct {
		AddSrc []string `json:"add_src"`
	} `json:"options"`
}

func loadSpecs(path string) (map[int32]EffectSpec, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var entries []catalogEntry
	if err := json.Unmarshal(raw, &entries); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	out := make(map[int32]EffectSpec, len(entries))
	for _, e := range entries {
		s := EffectSpec{
			ID:       e.ID,
			Name:     e.CName,
			ExecType: e.ExecType,
			DataSize: e.DataStructSize,
			BodySize: e.PacketBodySize,
		}
		if len(e.Members) > 0 {
			m := e.Members[0]
			s.HasName = m.Name == "name" && m.CType == "int" && m.Pointer == 0 && (m.ArrayLen == nil || *m.ArrayLen == 0)
		}
		if len(e.Options.AddSrc) > 0 {
			s.AddSrc = append([]string(nil), e.Options.AddSrc...)
		}
		out[e.ID] = s
	}
	return out, nil
}
